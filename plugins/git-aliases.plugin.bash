# about: short git commands as abbreviations (expand as you type): g gs ga gc gco gb gd gl gp gpl gst
abbr -a g   git
abbr -a gs  git status
abbr -a ga  git add
abbr -a gc  git commit
abbr -a gco git checkout
abbr -a gb  git branch
abbr -a gd  git diff
abbr -a gl  git log --oneline --graph --decorate
abbr -a gp  git push
abbr -a gpl git pull
abbr -a gst git stash
